#!/usr/bin/env python3
"""Generate the one-file AI review bundle and the per-file source map.

The bundle concatenates the design and evidence documents so an automated
reviewer needs one fetch instead of the GitHub code browser. The source map
lists every tracked file with its blob SHA-256 and an immutable raw URL.
"""
from __future__ import annotations

import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

BUNDLE_FILES = [
    "README.md",
    "SECURITY.md",
    "SECURITY_LIMITATIONS.md",
    "docs/THREAT_MODEL.md",
    "docs/CRYPTO.md",
    "docs/network/NETWORK_GUIDE.md",
    "docs/PRIVACY.md",
    "docs/DATA_CONTROL.md",
    "docs/CLAIM_REGISTER.md",
    "docs/PROOF_MATRIX.md",
    "docs/HARDENING_REPORT.md",
    "docs/HARDENING_BASELINE.md",
    "docs/SECURITY_SCORECARD.md",
    "docs/KNOWN_LIMITATIONS.md",
    "docs/BACKUP_AND_RECOVERY.md",
    "docs/COLD_WALLET.md",
    "docs/TESTING.md",
]


def git(*args: str) -> str:
    return subprocess.check_output(["git", *args], cwd=ROOT, text=True).strip()


def main() -> int:
    commit = git("rev-parse", "HEAD")
    short = commit[:12]
    out = [
        "# X Wallet — review bundle",
        "",
        f"Commit: `{commit}`",
        "This file concatenates the documents an automated reviewer needs.",
        "It is generated by `scripts/build_review_bundle.py`.",
        "",
    ]
    for rel in BUNDLE_FILES:
        path = ROOT / rel
        if not path.is_file():
            continue
        out += [f"---", "", f"## `{rel}`", "", path.read_text(encoding="utf-8").rstrip(), ""]
    (ROOT / "docs" / "REVIEW_BUNDLE.md").write_text("\n".join(out) + "\n", encoding="utf-8")

    raw = f"https://raw.githubusercontent.com/jackh0006/X-Wallet/{commit}"
    rows = [
        "# Source map",
        "",
        f"Commit: `{commit}`",
        "",
        "Every tracked file with its git blob SHA-1, size and an immutable raw URL.",
        "Use the raw URL when the GitHub code browser is unavailable.",
        "",
        "| Path | Bytes | Blob SHA-1 | Raw |",
        "|---|---:|---|---|",
    ]
    listing = git("ls-tree", "-r", "-l", commit).splitlines()
    for line in listing:
        meta, path = line.split("\t", 1)
        mode, kind, blob, size = meta.split()
        if kind != "blob":
            continue
        rows.append(f"| `{path}` | {size} | `{blob}` | {raw}/{path} |")
    (ROOT / "docs" / "SOURCE_MAP.md").write_text("\n".join(rows) + "\n", encoding="utf-8")
    print(f"wrote docs/REVIEW_BUNDLE.md and docs/SOURCE_MAP.md for {short}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
